        public async Task<WeatherForecast[]> GetWeatherForecast()
        {
            string token = await localStorageService.GetItemAsStringAsync("token");
            var claims = Generics.GetClaimsFromToken(token);
            string role = claims.Role;
            httpClient.DefaultRequestHeaders.Authorization = new System.Net.Http.Headers.AuthenticationHeaderValue("Bearer", token);
            HttpResponseMessage? response;
            if (role == "Admin")
                response = await httpClient.GetAsync("api/WeatherForecast/admin");
            else
                response = await httpClient.GetAsync("api/WeatherForecast/user");

            //Read Response
            if (!response.IsSuccessStatusCode)
                return null;

            var result = await response.Content.ReadAsStringAsync();
            return [.. Generics.DeserializeJsonStringList<WeatherForecast>(result)];
        }


